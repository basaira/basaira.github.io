function formOdInjectSubmitCaption(form, copy) {
  const submit = form.querySelector('button[type="submit"]');
  if (!submit) return null;
  if (!submit.querySelector('.submit-seal')) {
    const seal = document.createElement('span');
    seal.className = 'submit-seal';
    seal.textContent = copy.seal;
    submit.appendChild(seal);
  }
  let caption = form.querySelector('.form-submit-caption');
  if (!caption) {
    caption = document.createElement('div');
    caption.className = 'form-submit-caption';
    caption.innerHTML = `<span class="form-submit-caption__state" data-submit-state>${copy.statusIdle}</span><span class="form-submit-caption__hint" data-submit-hint>${copy.hintIdle}</span>`;
    submit.insertAdjacentElement('afterend', caption);
  }
  return caption;
}

function formOdDecorateFields(form, config, copy) {
  formOdGetFieldBlocks(form, config.fieldsSelector).forEach((block) => {
    const control = formOdFieldInput(block);
    if (!control) return;
    block.classList.add('overdrive-field');
    block.dataset.fieldName = control.name;
    const label = block.querySelector('label');
    if (label && !label.querySelector('.field-status-badge')) {
      const badge = document.createElement('span');
      badge.className = 'field-status-badge';
      badge.setAttribute('aria-hidden', 'true');
      badge.textContent = '•';
      label.appendChild(badge);
    }
    if (!block.querySelector('.field-status-row')) {
      const status = document.createElement('div');
      status.className = 'field-status-row';
      const optional = !control.required && !['track', 'whatsapp', 'email', 'phone', 'country', 'fullName'].includes(control.name);
      const meta = optional ? copy.optional : copy.required;
      status.innerHTML = `<span class="field-status-copy">${copy.pending}</span><span class="field-status-meta">${meta}</span>`;
      block.appendChild(status);
    }
    control.addEventListener('focus', () => block.classList.add('is-focused'));
    control.addEventListener('blur', () => block.classList.remove('is-focused'));
  });
}

function formOdValidate(control, config) {
  const name = control.name;
  const value = formOdSafeText(control.value);
  const copy = formOdCopy();

  if (name === 'fullName') {
    if (!value) return { state: 'empty', message: copy.pending };
    return value.length >= 2 ? { state: 'valid', message: copy.valid } : { state: 'invalid', message: copy.required };
  }
  if (name === 'country') {
    if (!value) return { state: 'empty', message: copy.pending };
    return value.length >= 2 ? { state: 'valid', message: copy.valid } : { state: 'invalid', message: copy.required };
  }
  if (name === 'phone' || name === 'whatsapp') {
    if (!value) return { state: 'empty', message: copy.pending };
    const digits = value.replace(/\D/g, '');
    return digits.length >= 6 && digits.length <= 15 ? { state: 'valid', message: copy.valid } : { state: 'invalid', message: copy.required };
  }
  if (name === 'email') {
    if (!value) return { state: 'empty', message: copy.optional };
    return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value) ? { state: 'valid', message: copy.valid } : { state: 'invalid', message: copy.required };
  }
  if (name === 'track' || name === 'contactPreference') {
    if (!value) return { state: 'empty', message: copy.pending };
    return { state: 'valid', message: copy.valid };
  }
  if (name === 'age') {
    if (!value) return { state: 'empty', message: copy.optional };
    return /^\d{1,2}$/.test(value) && Number(value) >= 3 && Number(value) <= 99 ? { state: 'valid', message: copy.valid } : { state: 'invalid', message: copy.required };
  }
  if (name === 'message' || name === 'goal' || name === 'preferredTime' || name === 'ageGroup') {
    if (!value) return { state: 'empty', message: copy.optional };
    return { state: 'valid', message: copy.valid };
  }
  return value ? { state: 'valid', message: copy.valid } : { state: 'empty', message: copy.pending };
}

function formOdUpdateFieldState(block, config) {
  const control = formOdFieldInput(block);
  if (!control) return 'empty';
  const copy = formOdCopy();
  const validation = formOdValidate(control, config);
  block.classList.remove('is-valid', 'is-invalid');
  if (validation.state === 'valid') block.classList.add('is-valid');
  if (validation.state === 'invalid') block.classList.add('is-invalid');
  const badge = block.querySelector('.field-status-badge');
  if (badge) badge.textContent = validation.state === 'valid' ? '✓' : validation.state === 'invalid' ? '!' : '•';
  const copyEl = block.querySelector('.field-status-copy');
  if (copyEl) copyEl.textContent = validation.message;
  const metaEl = block.querySelector('.field-status-meta');
  if (metaEl && validation.state === 'valid') metaEl.textContent = copy.valid;
  else if (metaEl) {
    const optional = !control.required && !['track', 'whatsapp', 'email', 'phone', 'country', 'fullName'].includes(control.name);
    metaEl.textContent = optional ? copy.optional : copy.required;
  }
  return validation.state;
}

function formOdGetRequiredControls(form, config) {
  const byName = (name) => form.elements.namedItem(name);
  const controls = config.required.map(byName).filter(Boolean);
  if (config.either) {
    config.either.forEach((pair) => {
      pair.forEach((name) => {
        const control = byName(name);
        if (control && !controls.includes(control)) controls.push(control);
      });
    });
  }
  return controls;
}

function formOdUpdateProgress(form, config, copy) {
  const requiredControls = formOdGetRequiredControls(form, config);
  const total = config.required.length + (config.either?.length || 0);
  let complete = 0;
  let remaining = 0;
  const nameToControl = (name) => form.elements.namedItem(name);

  config.required.forEach((name) => {
    const control = nameToControl(name);
    const state = control ? formOdValidate(control, config).state : 'empty';
    if (state === 'valid') complete += 1;
    else remaining += 1;
  });

  (config.either || []).forEach((group) => {
    const okay = group.some((name) => formOdValidate(nameToControl(name), config).state === 'valid');
    if (okay) complete += 1;
    else remaining += 1;
  });

  const percent = total ? Math.round((complete / total) * 100) : 0;
  const fill = form.querySelector('[data-form-progress-fill]');
  const completeEl = form.querySelector('[data-form-complete]');
  const totalEl = form.querySelector('[data-form-total]');
  const progressCopy = form.querySelector('[data-form-progress-copy]');
  const helper = form.querySelector('[data-form-progress-helper]');
  const readiness = form.querySelector('[data-form-readiness]');
  if (fill) fill.style.inlineSize = `${percent}%`;
  if (completeEl) completeEl.textContent = String(complete);
  if (totalEl) totalEl.textContent = String(total);
  if (progressCopy) progressCopy.textContent = `${complete} ${copy.of} ${total} ${copy.complete}`;
  if (helper) helper.textContent = remaining === 0 ? copy.ready : `${remaining} ${copy.fieldsLeft}. ${copy.progressHint}`;
  if (readiness) readiness.textContent = remaining === 0 ? copy.ready : copy.inProgress;
  form.dataset.formReady = remaining === 0 ? 'true' : 'false';
}

function formOdSerialize(form) {
  const payload = {};
  Array.from(form.elements).forEach((el) => {
    if (!el.name || el.type === 'submit' || el.name === 'website') return;
    payload[el.name] = el.value;
  });
  return payload;
}

function formOdRestore(form, key, copy) {
  const draft = formOdReadDraft(key);
  let restored = false;
  Object.entries(draft).forEach(([name, value]) => {
    const control = form.elements.namedItem(name);
    if (!control || typeof value !== 'string') return;
    if (!control.value) {
      control.value = value;
      restored = restored || Boolean(value);
    }
  });
  if (restored) {
    const helper = form.querySelector('[data-form-progress-helper]');
    if (helper) helper.textContent = copy.restore;
  }
}

function formOdSetSubmitState(form, state, copy) {
  /*
   * Main-thread safety: this form is watched by a MutationObserver below.
   * Rewriting the observer's own text nodes on every callback creates a
   * self-sustaining childList mutation loop and can freeze the whole page.
   * Keep the same UI/state logic, but make DOM writes idempotent.
   */
  if (form.dataset.overdriveSubmitState !== state) {
    form.dataset.overdriveSubmitState = state;
  }

  const stateEl = form.querySelector('[data-submit-state]');
  const hintEl = form.querySelector('[data-submit-hint]');
  if (!stateEl || !hintEl) return;

  let nextState = copy.statusIdle;
  let nextHint = copy.hintIdle;

  if (state === 'submitting') {
    nextState = copy.statusSubmitting;
    nextHint = copy.hintSubmitting;
  } else if (state === 'success') {
    nextState = copy.statusSuccess;
    nextHint = copy.hintSuccess;
  } else if (state === 'error') {
    nextState = copy.statusError;
    nextHint = copy.hintError;
  }

  if (stateEl.textContent !== nextState) stateEl.textContent = nextState;
  if (hintEl.textContent !== nextHint) hintEl.textContent = nextHint;
}

function formOdWatchSubmitState(form, key, copy) {
  const submit = form.querySelector('button[type="submit"]');
  const successEl = form.querySelector('#success-message, #post-submit.is-success, #post-submit, #form-status');
  const errorEl = form.querySelector('#error-message, #form-status');
  const computeState = () => {
    const successShown = !!form.querySelector('#success-message:not(.hidden)') || form.dataset.delightState === 'received' || form.querySelector('#post-submit.show.is-success');
    const errorShown = !!form.querySelector('#error-message:not(.hidden)') || form.dataset.delightState === 'recovery' || form.querySelector('#form-status.show.error');
    const busy = form.getAttribute('aria-busy') === 'true' || submit?.getAttribute('aria-busy') === 'true' || submit?.classList.contains('is-loading');
    if (busy) return 'submitting';
    if (successShown) return 'success';
    if (errorShown) return 'error';
    return 'idle';
  };
  const sync = () => {
    const state = computeState();
    formOdSetSubmitState(form, state, copy);
    if (state === 'success') formOdClearDraft(key);
  };
  const observer = new MutationObserver(sync);
  observer.observe(form, { attributes: true, subtree: true, childList: true, attributeFilter: ['class', 'aria-busy', 'data-delight-state', 'style'] });
  sync();
}

function formOdInstall(form, config) {
  const copy = formOdCopy();
  const key = formOdStorageKey(config);
  form.classList.add('overdrive-form');
  form.dataset.overdriveSubmitState = 'idle';
  formOdInjectPanel(form, config, copy);
  formOdInsertSectionPills(form, config, copy);
  formOdInjectSubmitCaption(form, copy);
  formOdDecorateFields(form, config, copy);
  formOdRestore(form, key, copy);

  const blocks = formOdGetFieldBlocks(form, config.fieldsSelector);
  const refresh = () => {
    blocks.forEach((block) => formOdUpdateFieldState(block, config));
    formOdUpdateProgress(form, config, copy);
    formOdWriteDraft(key, formOdSerialize(form));
  };

  blocks.forEach((block) => {
    const control = formOdFieldInput(block);
    if (!control) return;
    ['input', 'change', 'blur'].forEach((eventName) => control.addEventListener(eventName, refresh));
  });

  form.addEventListener('submit', () => {
    blocks.forEach((block) => formOdUpdateFieldState(block, config));
    formOdUpdateProgress(form, config, copy);
    formOdSetSubmitState(form, 'submitting', copy);
  });

  form.addEventListener('reset', () => {
    window.setTimeout(() => {
      blocks.forEach((block) => block.classList.remove('is-valid', 'is-invalid'));
      formOdSetSubmitState(form, 'idle', copy);
      formOdUpdateProgress(form, config, copy);
      formOdClearDraft(key);
    }, 10);
  });

  formOdWatchSubmitState(form, key, copy);
  refresh();
}

window.addEventListener('DOMContentLoaded', () => {
  Object.values(FORM_OD_CONFIG).forEach((config) => {
    const form = document.getElementById(config.id);
    if (form) formOdInstall(form, config);
  });
});

function formOdLocale() {
  const raw = (document.documentElement.lang || document.body?.dataset?.locale || 'en').toLowerCase();
  return FORM_OD_COPY[raw] ? raw : 'en';
}

function formOdCopy() { return FORM_OD_COPY[formOdLocale()] || FORM_OD_COPY.en; }

function formOdSafeText(value) { return typeof value === 'string' ? value.trim() : ''; }

function formOdGetFieldBlocks(form, selector) {
  return Array.from(form.querySelectorAll(selector)).filter((block) => block.querySelector('input, select, textarea'));
}

function formOdFieldInput(block) { return block.querySelector('input, select, textarea'); }

function formOdStorageKey(config) {
  return `${config.storagePrefix}:${window.location.pathname}`;
}

function formOdReadDraft(key) {
  try {
    return JSON.parse(localStorage.getItem(key) || '{}');
  } catch (_) {
    return {};
  }
}

function formOdWriteDraft(key, payload) {
  try { localStorage.setItem(key, JSON.stringify(payload)); } catch (_) {}
}

function formOdClearDraft(key) {
  try { localStorage.removeItem(key); } catch (_) {}
}

function formOdInsertSectionPills(form, config, copy) {
  const grid = form.querySelector(config.gridSelector);
  if (!grid || grid.querySelector('.form-section-pill')) return;
  const blocks = formOdGetFieldBlocks(form, config.fieldsSelector);
  const stepMap = {
    1: { title: copy.step1, hint: copy.step1Hint },
    2: { title: copy.step2, hint: copy.step2Hint },
    3: { title: copy.step3, hint: copy.step3Hint }
  };
  config.sectionAnchors.forEach((anchor) => {
    const block = blocks.find((item) => formOdFieldInput(item)?.name === anchor.name);
    if (!block) return;
    const pill = document.createElement('div');
    pill.className = 'form-section-pill';
    pill.innerHTML = `<span class="form-section-pill__number">0${anchor.step}</span><span class="form-section-pill__copy"><span>${stepMap[anchor.step].title}</span><small>${stepMap[anchor.step].hint}</small></span>`;
    grid.insertBefore(pill, block);
  });
}

